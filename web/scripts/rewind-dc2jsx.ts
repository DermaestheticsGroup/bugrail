// Converts the claude.ai/design DC template (design/rewind/template.html) into a React view
// (app/rewind/_app/view.tsx) plus the hover stylesheet it needs (app/rewind/_app/hover.css).
// Run: bun scripts/rewind-dc2jsx.ts
import { parseDocument } from "htmlparser2";
import type { ChildNode, Element } from "domhandler";

const src = await Bun.file("design/rewind/template.html").text();
const body = src.slice(src.indexOf("</helmet>") + "</helmet>".length);
const doc = parseDocument(body, { lowerCaseAttributeNames: false, lowerCaseTags: true, recognizeSelfClosing: true });

const hover = new Map<string, string>();
const hoverClass = (pseudo: string, css: string) => {
  const k = pseudo + "|" + css;
  if (!hover.has(k)) hover.set(k, "scp" + hover.size.toString(36));
  return hover.get(k)!;
};

const ATTR: Record<string, string> = {
  class: "className", for: "htmlFor", autofocus: "autoFocus", readonly: "readOnly",
  tabindex: "tabIndex", maxlength: "maxLength", spellcheck: "spellCheck",
};
const camel = (s: string) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

// `{{ a.b }}` path -> JS expression; loop vars resolve locally, everything else from `v`
const expr = (path: string, scope: Set<string>) => {
  const parts = path.trim().split(".");
  const root = scope.has(parts[0]) ? parts[0] : "v." + parts[0];
  return [root, ...parts.slice(1)].join("?.");
};
const WHOLE = /^\s*\{\{([\s\S]+?)\}\}\s*$/;
const attrExpr = (raw: string, scope: Set<string>) => {
  const m = raw.match(WHOLE);
  if (m) return expr(m[1], scope);
  if (!raw.includes("{{")) return JSON.stringify(raw);
  const parts = raw.split(/\{\{([\s\S]+?)\}\}/g);
  return "`" + parts.map((s, i) => (i & 1 ? "${" + expr(s, scope) + ' ?? ""}' : s.replace(/[`\\$]/g, "\\$&"))).join("") + "`";
};
const cssObj = (css: string) => {
  const o: Record<string, string> = {};
  for (const decl of css.split(";")) {
    const i = decl.indexOf(":");
    if (i < 0) continue;
    const p = decl.slice(0, i).trim();
    o[p.startsWith("--") ? p : camel(p)] = decl.slice(i + 1).trim();
  }
  return JSON.stringify(o);
};

function props(el: Element, scope: Set<string>) {
  const out: string[] = [];
  const classes: string[] = [];
  for (const [name, value] of Object.entries(el.attribs)) {
    if (name.startsWith("hint-")) continue;
    if (name.startsWith("style-")) { classes.push(hoverClass(name.slice(6), value)); continue; }
    let key = ATTR[name] ?? name;
    if (!key.startsWith("aria-") && !key.startsWith("data-") && key.includes("-")) key = camel(key);
    if (key === "style") {
      out.push(value.includes("{{") ? `style={css(${attrExpr(value, scope)})}` : `style={${cssObj(value)}}`);
      continue;
    }
    if (value === "" && ["autoFocus", "disabled", "checked", "readOnly", "draggable", "multiple"].includes(key)) {
      out.push(`${key}={true}`);
      continue;
    }
    let e = attrExpr(value, scope);
    if (key === "value") e = `(${e}) ?? ""`;
    if (key === "checked") e = `!!(${e})`;
    out.push(`${key}={${e}}`);
  }
  if (classes.length) out.push(`className=${JSON.stringify(classes.join(" "))}`);
  return out.join(" ");
}

function kids(nodes: ChildNode[], scope: Set<string>): string {
  return nodes.map((n) => node(n, scope)).join("");
}

function node(n: ChildNode, scope: Set<string>): string {
  if (n.type === "text") {
    const t = n.data.replace(/\s+/g, " ");
    if (!t) return "";
    const parts = t.split(/\{\{([\s\S]+?)\}\}/g);
    return parts.map((s, i) => (i & 1 ? `{${expr(s, scope)}}` : s ? `{${JSON.stringify(s)}}` : "")).join("");
  }
  if (n.type === "comment") return "";
  if (n.type !== "tag" && n.type !== "script" && n.type !== "style") return "";
  const el = n as Element;
  const tag = el.name;
  if (tag === "sc-if") {
    return `{(${attrExpr(el.attribs.value, scope)}) ? <>${kids(el.children, scope)}</> : null}`;
  }
  if (tag === "sc-for") {
    const as = el.attribs.as || "item";
    const inner = new Set(scope).add(as);
    return `{asList(${attrExpr(el.attribs.list, scope)}).map((${as}: any, ${as}$i: number) => <Fragment key={${as}$i}>${kids(el.children, inner)}</Fragment>)}`;
  }
  if (tag === "x-import") {
    const comp = el.attribs["component-from-global-scope"].split(".").pop();
    const p = Object.entries(el.attribs)
      .filter(([k]) => k !== "component-from-global-scope")
      .map(([k, v]) => (k === "hint-size" ? `hintSize={${JSON.stringify(v)}}` : `${camel(k)}={${attrExpr(v, scope)}}`))
      .join(" ");
    return `<${comp} ${p} />`;
  }
  const p = props(el, scope);
  const c = kids(el.children, scope);
  return c ? `<${tag} ${p}>${c}</${tag}>` : `<${tag} ${p} />`;
}

const jsx = kids(doc.children, new Set());
const out = `// GENERATED by scripts/rewind-dc2jsx.ts from design/rewind/template.html — do not edit by hand.
/* eslint-disable */
// @ts-nocheck
import { Fragment } from "react";
import { AppStatusBadge, PatientInitialsAvatar } from "./ds";
import { css, asList } from "./css";

export function View({ v }: { v: any }) {
  return <>${jsx}</>;
}
`;
await Bun.write("app/rewind/_app/view.tsx", out);

const importantify = (css: string) =>
  css.split(";").filter((d) => d.trim()).map((d) => (d.includes("!important") ? d : d + " !important")).join(";");
await Bun.write(
  "app/rewind/_app/hover.css",
  [...hover].map(([k, cls]) => {
    const [pseudo, ...rest] = k.split("|");
    const css = rest.join("|");
    const pe = pseudo === "before" || pseudo === "after";
    return `.${cls}${pe ? "::" : ":"}${pseudo}{${pe ? css : importantify(css)}}`;
  }).join("\n") + "\n",
);
console.log(`view.tsx ${out.length}b, ${hover.size} hover classes`);
